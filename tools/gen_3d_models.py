def box_faces(x0, y0, z0, x1, y1, z1):
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    f = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    return v, f


def write_wrl(name, boxes):
    s = 1 / 2.54   # KiCad VRML units: 0.1 inch
    out = ["#VRML V2.0 utf8", f"# {name} - generated by tools/gen_3d_models.py"]
    for x0, y0, z0, x1, y1, z1, c in boxes:
        v, f = box_faces(x0, y0, z0, x1, y1, z1)
        pts = ", ".join(f"{a * s:.5f} {b * s:.5f} {d * s:.5f}" for a, b, d in v)
        idx = ", ".join(" ".join(str(i) for i in q) + " -1" for q in f)
        out.append("Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f "
                   "specularColor 0.2 0.2 0.2 shininess 0.3 } }" % c)
        out.append("  geometry IndexedFaceSet { solid TRUE coord Coordinate { point [ %s ] } coordIndex [ %s ] } }" % (pts, idx))
    open(os.path.join(OUT, name + ".wrl"), "w").write("\n".join(out) + "\n")


for name, boxes in MODELS.items():
    write_wrl(name, boxes)

try:
    import FreeCAD as App   # freecadcmd only
    import Part
    for name, boxes in MODELS.items():
        shapes = [Part.makeBox(x1 - x0, y1 - y0, z1 - z0, App.Vector(x0, y0, z0)) for x0, y0, z0, x1, y1, z1, _ in boxes]
        comp = shapes[0].fuse(shapes[1:]) if len(shapes) > 1 else shapes[0]
        comp.exportStep(os.path.join(OUT, name + ".step"))
    print("wrl + step in", os.path.abspath(OUT))
except ImportError:
    print("wrl in", os.path.abspath(OUT), "(STEP: run with freecadcmd)")
