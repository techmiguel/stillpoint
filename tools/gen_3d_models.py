"""Simple 3D models (dimensioned boxes) of the custom parts in hardware/lib/radar60.pretty.

Writes a coloured .wrl per part (KiCad 3D viewer) and, when run with the
FreeCAD interpreter, the .step as well (the board STEP export: kicad-cli
swaps the .wrl for the .step of the same name).

  python tools/gen_3d_models.py                       -> .wrl only
  "C:\\Program Files\\FreeCAD 1.1\\bin\\freecadcmd.exe" -c "exec(open(r'tools/gen_3d_models.py').read())"   -> .wrl + .step

Millimetres, footprint frame with Y up (KiCad flips Y when it places
the model): a footprint point (x, y) is (x, -y) here.
"""
